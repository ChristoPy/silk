export function round(n) {
  return Math.round(n);
}

export function floor(n) {
  return Math.floor(n);
}

export function ceil(n) {
  return Math.ceil(n);
}

export function abs(n) {
  return Math.abs(n);
}

export function min(a, b) {
  return Math.min(a, b);
}

export function max(a, b) {
  return Math.max(a, b);
}

export function parse(s) {
  return Number(s);
}
